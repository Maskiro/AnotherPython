text = input('Введите текст для подсчета букв, цифр, симвалов!')
words = len(text.split())
letter = sum(1 for char in text if char.isalpha())
digit = sum(1 for char in text if char.isdigit())
tot = len(text)
print(f'Сколько слов: {words}')
print(f'Сколько букв: {letter}')
print(f'Сколько цифр: {digit}')
print(f'Сколько всего символов: {tot}')